// ==============================================================================
// 全量 MDI 图标加载器（约 7000 个图标 / 源 6.3MB）
// ------------------------------------------------------------------------------
// 只有「按图标名字取 path」的场景才需要全量（插件卡片图标、插件桥给插件用的 mdiJs）。
// 主包里有 60 多个文件用 **ESM 具名导入** `@mdi/js`（可被 tree-shake，只保留用到的
// 那几十个图标，体积可忽略）。
//
// ⚠️ 这里刻意 import 包的 **CJS 入口**（`@mdi/js/commonjs/mdi.js`）而不是 ESM 入口：
//    如果这里也 import 同一个 ESM 模块，webpack 会因为「命名空间导入需要全部导出」
//    把整包提升到 **main** 里（和主包的具名导入共享同一模块实例）。
//    实测就是这样：主包 6.1MB，里面躺着全部 7000 个图标。
//    换成 CJS 入口 = 另一个模块实例 → 整包只会出现在这个**异步 chunk** 中，
//    首屏主包保持精简（~1.5-2MB），插件功能完全不受影响。
// ==============================================================================

let _promise = null;

/** 异步拿到「全部图标」的对象（name -> svg path）。结果会被缓存。 */
export default function loadAllMdi() {
  if (!_promise) {
    _promise = import(/* webpackChunkName: "mdi-full" */ '@mdi/js/commonjs/mdi.js')
      .then((mod) => (mod && mod.default) || mod || {})
      .catch((err) => {
        // 失败不缓存，下次还能重试
        _promise = null;
        throw err;
      });
  }
  return _promise;
}
